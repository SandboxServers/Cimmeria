const gigabytes=(bytes:number)=>`${(bytes/1e9).toFixed(1)} GB`;
/** The copy for `code`, with `{needed}` and `{free}` filled from the facts given (bytes, shown as GB). */
export const failureText=(code:FailureCode,facts?:{needed?:number;free?:number}):{message:string;fix:string}=>{
 const fill=(text:string)=>text
  .replace('{needed}',facts?.needed===undefined?'{needed}':gigabytes(facts.needed))
  .replace('{free}',facts?.free===undefined?'{free}':gigabytes(facts.free));
 const copy=failureCopy[code];
 return {message:fill(copy.message),fix:fill(copy.fix)};
};
