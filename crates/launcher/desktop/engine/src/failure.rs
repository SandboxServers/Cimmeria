//! The launcher's closed failure taxonomy (C-PD1): one code per way an action can
//! fail, shared with the frontend through `frontend/src/failure-codes.json`.
//!
//! The codes and their order are a wire contract: the webview decodes them with a
//! closed literal list and picks the player's copy from `failure-copy.ts`.

/// Why a launcher action failed, as a closed snake_case code.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FailureCode {
    RosettaMissing,
    RosettaCheckTimedOut,
    RosettaInstallFailed,
    RosettaInstallDeclined,
    WineRuntimeMissing,
    WineRuntimeDownloadFailed,
    WineRuntimeInvalid,
    WineRuntimeBusy,
    WineRuntimeUnavailable,
    HelperUnavailable,
    AppTranslocated,
    PhysxMissing,
    PhysxInstallFailed,
    PrerequisitesMissing,
    DiskSpaceLow,
    GameFolderNotChosen,
    GameFolderMissing,
    GameFolderInvalid,
    GameFolderNotWritable,
    GameFilesInvalid,
    StateCorrupt,
    LocalIo,
    ManifestUnreachable,
    ManifestInvalid,
    SigningKeyUnavailable,
    DownloadFailed,
    OperationBusy,
    StatusStale,
    IdentityConflict,
    RecoveryRequired,
    PersistenceUncertain,
    RepairNotStarted,
    InstallInterrupted,
    InstallFailed,
    LauncherTooOld,
    PlatformUnsupported,
    LaunchResourcesMissing,
    LoginServersInvalid,
    LaunchPrepareFailed,
    TicketUnavailable,
    SignInEnded,
    SpawnFailed,
    SpawnPermissionDenied,
    SpawnNotFound,
    GameExitedNonzero,
    GameStatusUnknown,
    GameWindowHidden,
    DisplaySettingsNotApplied,
    Unknown,
}

