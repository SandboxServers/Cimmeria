def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def normalize_row(raw: dict, where: str) -> dict:
    row = {}
    for col in COLUMNS:
        value = raw.get(col)
        if col in INT_COLUMNS:
            if value is None or value == "":
                value = 0
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise InputError(f"{where}: {col} is not an integer: {value!r}")
            if isinstance(value, float):
                if not value.is_integer():
                    raise InputError(f"{where}: {col} is not an integer: {value!r}")
                value = int(value)
        elif col in BOOL_COLUMNS:
            if not isinstance(value, bool):
                raise InputError(f"{where}: {col} is not a boolean: {value!r}")
        elif col == "additional_prereq_ability_ids":
            # A single id may arrive as a number rather than text.
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                value = str(int(value))
            value = "" if value is None else str(value).strip()
        else:
            if not isinstance(value, str) or not value.strip():
                raise InputError(f"{where}: {col} is empty or not text: {value!r}")
            value = value.strip()
        row[col] = value
    return row


def load_from_workbook() -> list[dict]:
    path = REPO_ROOT / WORKBOOK
    if not path.is_file():
        raise InputError(f"workbook not found: {WORKBOOK.as_posix()}")
    actual = sha256_of(path)
    if actual != WORKBOOK_SHA256:
        raise InputError(
            f"workbook SHA-256 mismatch: expected {WORKBOOK_SHA256}, got {actual}. "
            "The canonical workbook changed; re-pin it deliberately."
        )
    try:
        import openpyxl  # noqa: PLC0415 - optional dependency, workbook mode only
    except ImportError as exc:
        raise InputError(
            "openpyxl is required to read the workbook (pip install openpyxl), "
            "or use --from-json to regenerate from the committed export"
        ) from exc
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    if SHEET not in wb.sheetnames:
        raise InputError(f"sheet {SHEET} missing from the workbook")
    rows = list(wb[SHEET].iter_rows(values_only=True))
    wb.close()
    if not rows:
        raise InputError(f"sheet {SHEET} is empty")
    header = tuple(str(c).strip() if c is not None else "" for c in rows[0])
    extra = header[len(COLUMNS):]
    if header[: len(COLUMNS)] != COLUMNS or any(extra):
        raise InputError(f"sheet {SHEET} header is {header}, expected {COLUMNS}")
    out = []
    for n, values in enumerate(rows[1:], start=2):
        if all(v is None or v == "" for v in values):
            continue
        out.append(normalize_row(dict(zip(COLUMNS, values)), f"{SHEET} row {n}"))
    return out


def load_from_json() -> list[dict]:
    path = REPO_ROOT / JSON_OUT
    if not path.is_file():
        raise InputError(f"committed export not found: {JSON_OUT.as_posix()}")
    data = json.loads(path.read_text(encoding="utf-8"))
    src = data.get("source", {})
    if src.get("sha256") != WORKBOOK_SHA256 or src.get("sheet") != SHEET:
        raise InputError(
            f"{JSON_OUT.as_posix()} was exported from {src}, not the pinned workbook"
        )
    return [
        normalize_row(raw, f"{JSON_OUT.as_posix()} rows[{i}]")
        for i, raw in enumerate(data.get("rows", []))
    ]


# --------------------------------------------------------------------------
# Minimal parser for the repo's one-row-per-statement INSERT seeds
# --------------------------------------------------------------------------

INSERT_RE = re.compile(
    r"^INSERT INTO (?:\w+\.)?(\w+) \(([^)]*)\) VALUES \((.*)\);$", re.DOTALL
)


def split_values(text: str, where: str) -> list[str]:
    values, buf, i, in_str = [], [], 0, False
    while i < len(text):
        ch = text[i]
        if in_str:
            if ch == "'":
                if i + 1 < len(text) and text[i + 1] == "'":
                    buf.append("'")
                    i += 2
                    continue
                in_str = False
            else:
                buf.append(ch)
        elif ch == "'":
            in_str = True
        elif ch == ",":
            values.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
        i += 1
    if in_str:
        raise InputError(f"{where}: unterminated string literal")
    values.append("".join(buf).strip())
    return values


def split_statements(text: str) -> list[tuple[int, str]]:
    """Split SQL text on top-level ';', dropping '--' comments outside strings.

    Returns (starting line number, statement text) pairs. String literals may
    span lines (abilities.sql has multi-line descriptions).
    """
    out, buf, i, line, start, in_str = [], [], 0, 1, None, False
    while i < len(text):
        ch = text[i]
        if in_str:
            buf.append(ch)
            if ch == "'":
                if i + 1 < len(text) and text[i + 1] == "'":
                    buf.append("'")
                    i += 1
                else:
                    in_str = False
        elif ch == "-" and text.startswith("--", i):
            end = text.find("\n", i)
            i = len(text) if end < 0 else end
            continue
        elif ch == ";":
            stmt = "".join(buf).strip()
            if stmt:
                out.append((start or line, stmt))
            buf, start = [], None
        else:
            if ch == "'":
                in_str = True
            if start is None and not ch.isspace():
                start = line
            buf.append(ch)
        if ch == "\n":
            line += 1
        i += 1
    if in_str:
        raise InputError("unterminated string literal")
    if "".join(buf).strip():
        out.append((start or line, "".join(buf).strip()))
    return out


def parse_inserts(rel: Path, table: str) -> list[dict]:
    """Parse the INSERT rows for ``table``; any other INSERT is an error."""
    path = REPO_ROOT / rel
    if not path.is_file():
        raise InputError(f"seed not found: {rel.as_posix()}")
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    rows = []
    try:
        statements = split_statements(text)
    except InputError as exc:
        raise InputError(f"{rel.as_posix()}: {exc}") from exc
    for n, stmt in statements:
        if not stmt.startswith("INSERT INTO"):
            continue
        m = INSERT_RE.match(stmt + ";")
        if not m or m.group(1) != table:
            raise InputError(f"{rel.as_posix()}:{n}: unexpected statement: {stmt[:120]}")
        cols = [c.strip() for c in m.group(2).split(",")]
        vals = split_values(m.group(3), f"{rel.as_posix()}:{n}")
        if len(cols) != len(vals):
            raise InputError(f"{rel.as_posix()}:{n}: {len(cols)} columns, {len(vals)} values")
        rows.append(dict(zip(cols, vals)))
    return rows


def load_repo_context() -> tuple[set[int], dict[str, dict[int, list[int]]], list[dict]]:
    ability_ids = {int(r["ability_id"]) for r in parse_inserts(ABILITIES_SQL, "abilities")}

    def_archetype = {
        int(r["char_def_id"]): r["archetype"]
        for r in parse_inserts(CHAR_CREATION_SQL, "char_creation")
    }
    starters: dict[str, dict[int, list[int]]] = collections.defaultdict(
        lambda: collections.defaultdict(list)
    )
    for r in parse_inserts(STARTER_SQL, "char_creation_abilities"):
        char_def = int(r["char_def_id"])
        if char_def not in def_archetype:
            raise InputError(
                f"{STARTER_SQL.as_posix()}: char_def_id {char_def} has no char_creation row"
            )
        starters[def_archetype[char_def]][int(r["ability_id"])].append(char_def)

    trainer_rows = parse_inserts(TRAINER_SQL, "trainer_abilities")
    return ability_ids, starters, trainer_rows


