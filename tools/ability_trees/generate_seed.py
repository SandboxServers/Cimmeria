def pick_eol(path: Path, mode: str) -> str:
    if mode == "lf":
        return "\n"
    if mode == "crlf":
        return "\r\n"
    if path.is_file():
        head = path.read_bytes()[:4096]
        if b"\n" in head:
            return "\r\n" if b"\r\n" in head else "\n"
    return "\r\n" if os.name == "nt" else "\n"


def print_summary(rows: list[dict], notes: list[str], preserved: int) -> None:
    s = summarize(rows)
    print("Ability-tree seed validation: OK")
    print(f"  workbook      {WORKBOOK.name}")
    print(f"  sha256        {WORKBOOK_SHA256}")
    print(f"  nodes         {s['nodes']}")
    print(f"  unique ids    {s['unique_ids']}")
    print(f"  branches      {s['branches']}")
    print(f"  shared ids    {s['shared_ids']}")
    print(f"  raw cost 0    {s['raw_cost_zero']}")
    print(f"  above lvl 20  {s['above_level_20']}")
    print("  per archetype:")
    for label, enum, branches in ARCHETYPES:
        sizes = ", ".join(f"{b} {s['per_branch'][(label, b)]}" for b in branches)
        print(f"    {label:<22} {enum:<24} {s['per_archetype'][label]:>3}  ({sizes})")
    print("    (ARCHETYPE_Jaffa             no rows, D-AT04)")
    print(f"  trainer list {TRAINER_DEBUG_LIST_ID} rows: {s['nodes']}; other-list rows kept: {preserved}")
    for note in notes:
        print(f"  note: {note}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="regenerate in memory and exit 1 on drift")
    ap.add_argument(
        "--from-json",
        action="store_true",
        help="read the committed JSON export instead of the workbook (no openpyxl needed)",
    )
    ap.add_argument(
        "--eol",
        choices=("auto", "lf", "crlf"),
        default="auto",
        help="line endings for written files (auto: keep each file's current style)",
    )
    args = ap.parse_args(argv)

    try:
        rows = load_from_json() if args.from_json else load_from_workbook()
        ability_ids, starters, trainer_rows = load_repo_context()
        errors, notes = validate(rows, ability_ids, starters)
    except InputError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    if errors:
        print(f"Ability-tree seed validation FAILED ({len(errors)} problem(s)):", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 2

    outputs = {
        TREE_SQL: render_tree_sql(rows),
        TRAINER_SQL: render_trainer_sql(rows, trainer_rows),
    }
    if not args.from_json:
        outputs[JSON_OUT] = render_json(rows)
    preserved = sum(1 for e in trainer_rows if int(e["list_id"]) != TRAINER_DEBUG_LIST_ID)

    print_summary(rows, notes, preserved)

    if args.check:
        drift = []
        for rel, text in outputs.items():
            path = REPO_ROOT / rel
            current = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.is_file() else None
            if current != text:
                drift.append(rel.as_posix())
        if drift:
            print("DRIFT: regenerate with tools/ability_trees/generate_seed.py:", file=sys.stderr)
            for d in drift:
                print(f"  - {d}", file=sys.stderr)
            return 1
        print("check: committed files match the generator")
        return 0

    for rel, text in outputs.items():
        path = REPO_ROOT / rel
        eol = pick_eol(path, args.eol)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.replace("\n", eol).encode("utf-8"))
        print(f"wrote {rel.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
