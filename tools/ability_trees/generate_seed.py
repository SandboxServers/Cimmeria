def sort_key(row: dict) -> tuple:
    return (
        ARCHETYPE_ORDER[row["archetype"]],
        TREE_INDEX[(row["archetype"], row["branch"])],
        row["node_order"],
    )


def sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def generated_note() -> str:
    return GENERATED_NOTE.format(sheet=SHEET, workbook=WORKBOOK.as_posix(), sha=WORKBOOK_SHA256)


