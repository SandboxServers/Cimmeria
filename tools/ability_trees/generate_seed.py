def prerequisites(row: dict) -> list[int]:
    ids = set()
    if row["primary_prereq_ability_id"]:
        ids.add(row["primary_prereq_ability_id"])
    for token in row["additional_prereq_ability_ids"].split(","):
        token = token.strip()
        if not token:
            continue
        if not token.isdigit():
            raise InputError(
                f"{row['archetype']} / {row['branch']} #{row['node_order']}: "
                f"bad additional prerequisite {token!r}"
            )
        ids.add(int(token))
    ids.discard(0)
    return sorted(ids)


def node_label(row: dict) -> str:
    return f"{row['archetype']} / {row['branch']} #{row['node_order']} (ability {row['ability_id']})"


def validate(
    rows: list[dict],
    ability_ids: set[int],
    starters: dict[str, dict[int, list[int]]],
) -> tuple[list[str], list[str]]:
    errors: list[str] = []
    notes: list[str] = []

    # Archetype and branch mapping (handoff 5.3, D-AT04).
    for r in rows:
        if r["archetype"] not in ARCHETYPE_ENUM:
            errors.append(f"{node_label(r)}: unknown archetype {r['archetype']!r}")
        elif (r["archetype"], r["branch"]) not in TREE_INDEX:
            errors.append(f"{node_label(r)}: branch {r['branch']!r} is not in the tree_index map")
    if errors:
        return errors, notes

    branches: dict[tuple[str, str], list[dict]] = collections.defaultdict(list)
    for r in rows:
        branches[(r["archetype"], r["branch"])].append(r)

    # Workbook order must agree with the pinned tree_index map.
    seen_order: dict[str, list[str]] = collections.defaultdict(list)
    for r in rows:
        if r["branch"] not in seen_order[r["archetype"]]:
            seen_order[r["archetype"]].append(r["branch"])
    for label, _, expected in ARCHETYPES:
        got = tuple(seen_order.get(label, ()))
        if got != expected:
            errors.append(
                f"{label}: workbook branch order {got} differs from the tree_index map {expected}"
            )

    # Every id and prerequisite exists in resources.abilities (5.1, 4).
    for r in rows:
        if r["ability_id"] <= 0 or r["ability_id"] not in ability_ids:
            errors.append(f"{node_label(r)}: ability id missing from {ABILITIES_SQL.as_posix()}")
        for p in prerequisites(r):
            if p not in ability_ids:
                errors.append(
                    f"{node_label(r)}: prerequisite {p} missing from {ABILITIES_SQL.as_posix()}"
                )

    # (archetype, ability_id) is unique; shared ids span archetypes only.
    per_arch_ids = collections.Counter((r["archetype"], r["ability_id"]) for r in rows)
    for (arch, aid), n in sorted(per_arch_ids.items()):
        if n > 1:
            errors.append(f"{arch}: ability {aid} appears {n} times in one archetype")

    for (arch, branch), nodes in branches.items():
        where = f"{arch} / {branch}"
        nodes.sort(key=lambda r: r["node_order"])
        orders = [r["node_order"] for r in nodes]
        if orders != list(range(1, len(nodes) + 1)):
            errors.append(f"{where}: node orders are not unique and contiguous from 1: {orders}")
        if len(nodes) > MAX_NODES_PER_BRANCH:
            errors.append(
                f"{where}: {len(nodes)} nodes, the client draws at most {MAX_NODES_PER_BRANCH}"
            )
        roots = [r for r in nodes if r["is_branch_root"]]
        caps = [r for r in nodes if r["is_capstone"]]
        if len(roots) != 1:
            errors.append(f"{where}: {len(roots)} branch roots, expected exactly 1")
        else:
            root = roots[0]
            if root["node_order"] != 1 or prerequisites(root):
                errors.append(f"{node_label(root)}: root must be node 1 with no prerequisites")
        if len(caps) != 1:
            errors.append(f"{where}: {len(caps)} capstones, expected exactly 1")
        for c in caps:
            if c["unlock_level"] != CAPSTONE_LEVEL:
                errors.append(f"{node_label(c)}: capstone unlocks at {c['unlock_level']}, not 50")
            if c["is_branch_root"]:
                errors.append(f"{node_label(c)}: node is both root and capstone")

        in_branch = {r["ability_id"]: r for r in nodes}
        prev = None
        for r in nodes:
            if r["unlock_level"] not in ALLOWED_LEVELS:
                errors.append(f"{node_label(r)}: unlock level {r['unlock_level']} not allowed")
            if r["skill_point_cost"] < 0:
                errors.append(f"{node_label(r)}: negative skill_point_cost")
            if r["required_branch_points"] < 0:
                errors.append(f"{node_label(r)}: negative required_branch_points")
            if r["raw_training_cost"] < 0:
                errors.append(f"{node_label(r)}: negative raw_training_cost")
            # Tiers advance with node order; spend gates never fall (5.12).
            if prev is not None:
                if r["unlock_level"] < prev["unlock_level"]:
                    errors.append(f"{node_label(r)}: unlock level falls behind node {prev['node_order']}")
                if r["required_branch_points"] < prev["required_branch_points"]:
                    errors.append(
                        f"{node_label(r)}: required_branch_points falls behind node {prev['node_order']}"
                    )
                if (
                    r["unlock_level"] == prev["unlock_level"]
                    and r["required_branch_points"] != prev["required_branch_points"]
                ):
                    errors.append(f"{node_label(r)}: two spend gates inside one unlock tier")
            prev = r
            prereqs = prerequisites(r)
            if not r["is_branch_root"] and not prereqs:
                errors.append(f"{node_label(r)}: non-root node has no prerequisite")
            for p in prereqs:
                if p == r["ability_id"]:
                    errors.append(f"{node_label(r)}: requires itself (5.10)")
                    continue
                dep = in_branch.get(p)
                if dep is None:
                    errors.append(f"{node_label(r)}: prerequisite {p} is not a node of this branch")
                    continue
                # 5.9: a prerequisite must be reachable no later than its dependant.
                if dep["unlock_level"] > r["unlock_level"]:
                    errors.append(
                        f"{node_label(r)}: prerequisite {p} unlocks later ({dep['unlock_level']})"
                    )
                if dep["required_branch_points"] > r["required_branch_points"]:
                    errors.append(f"{node_label(r)}: prerequisite {p} has a higher spend gate")

        # 5.11: no cycle in the branch prerequisite graph.
        state: dict[int, int] = {}

        def visit(aid: int, stack: list[int], _in_branch=in_branch, _where=where) -> None:
            state[aid] = 1
            for p in prerequisites(_in_branch[aid]):
                if p not in _in_branch or p == aid:
                    continue
                if state.get(p) == 1:
                    cycle = stack[stack.index(p):] + [p] if p in stack else [aid, p]
                    errors.append(f"{_where}: prerequisite cycle {' -> '.join(map(str, cycle))}")
                elif state.get(p) is None:
                    visit(p, stack + [p])
            state[aid] = 2

        for aid in sorted(in_branch):
            if aid not in state:
                visit(aid, [aid])

    # Starter collisions (audit A-26, D-AT09).
    used_exceptions = set()
    for r in rows:
        enum = ARCHETYPE_ENUM[r["archetype"]]
        defs = starters.get(enum, {}).get(r["ability_id"])
        if not defs:
            continue
        key = (enum, r["ability_id"])
        if key in ALLOWED_STARTER_COLLISIONS:
            used_exceptions.add(key)
            notes.append(
                f"allowed starter collision ({ALLOWED_STARTER_COLLISIONS[key]}): {node_label(r)} "
                f"is granted at creation to char_def {sorted(set(defs))}"
            )
        else:
            errors.append(
                f"{node_label(r)}: purchasable node is granted at creation to {enum} "
                f"char_def {sorted(set(defs))}; a player could never buy it"
            )
    for key in sorted(set(ALLOWED_STARTER_COLLISIONS) - used_exceptions):
        notes.append(f"allowed starter collision {key} no longer occurs; drop it from the script")

    # Pinned shape of the canonical workbook.
    stats = summarize(rows)
    for key in ("nodes", "unique_ids", "branches", "shared_ids", "raw_cost_zero", "above_level_20"):
        if stats[key] != EXPECTED[key]:
            errors.append(f"{key} = {stats[key]}, expected {EXPECTED[key]}")
    if stats["per_archetype"] != EXPECTED["per_archetype"]:
        errors.append(
            f"per-archetype counts {stats['per_archetype']} != {EXPECTED['per_archetype']}"
        )
    for label, _, _ in ARCHETYPES:
        n = stats["branches_per_archetype"].get(label, 0)
        if n != 3:
            errors.append(f"{label}: {n} branches, expected exactly 3 (5.3)")

    return errors, notes


def summarize(rows: list[dict]) -> dict:
    per_arch = collections.Counter(r["archetype"] for r in rows)
    archs_per_id: dict[int, set[str]] = collections.defaultdict(set)
    for r in rows:
        archs_per_id[r["ability_id"]].add(r["archetype"])
    branch_keys = {(r["archetype"], r["branch"]) for r in rows}
    return {
        "nodes": len(rows),
        "unique_ids": len(archs_per_id),
        "branches": len(branch_keys),
        "shared_ids": sum(1 for s in archs_per_id.values() if len(s) > 1),
        "raw_cost_zero": sum(1 for r in rows if r["raw_training_cost"] == 0),
        "above_level_20": sum(1 for r in rows if r["unlock_level"] > 20),
        "per_archetype": {label: per_arch.get(label, 0) for label, _, _ in ARCHETYPES},
        "branches_per_archetype": collections.Counter(a for a, _ in branch_keys),
        "per_branch": {
            (label, b): sum(1 for r in rows if r["archetype"] == label and r["branch"] == b)
            for label, _, bs in ARCHETYPES
            for b in bs
        },
    }


