"""Seed SQL for the Armory (campaign debug-armory, DR-03a): the item lists, the vendor templates and the spawns.

``debug_armory.py seed emit`` writes the three files from these functions. Each row copies the literals of the plaza
seed row it is based on (template 1302, spawn 13006); only the columns the Armory changes are rewritten.
"""

import sys
from pathlib import Path
from typing import Dict, List, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))
from seed_sql import read_text, sql_quote, sql_rows  # noqa: E402

SEEDS = Path("db/resources")
HEADING = -1.5708
SELL_LIST = 1349
ARMORY_LISTS = range(1310, 1349)
TEMPLATE_BASE, SPAWN_BASE, ITEM_ROW_BASE = 1610, 14110, 131000
ARMORY_WORLD = 1300
VENDOR_TEMPLATE = 1302  # the plaza munitions vendor: the row shape of every Armory vendor
VENDOR_SPAWN = 13006  # its spawn: the spawn shape
GENERATED = "-- Generated by tools/ability_mechanics/debug_armory.py seed emit (DR-03a). Do not edit: change the generator and rerun."


def raw_row(table: str, text: str, row: dict, **over: str) -> str:
    """An INSERT of ``row`` as the seed wrote it (its literals), with the columns in ``over`` replaced."""
    vals = [over.get(col, text[v.start : v.end]) for col, v in row.items()]
    return f"INSERT INTO {table} ({', '.join(row)}) VALUES ({', '.join(vals)});"


def seed_row(path: Path, table: str, key: str, value: str) -> Tuple[str, dict]:
    text, _ = read_text(SEEDS / path)
    return text, next(r for r in sql_rows(text, table) if r[key].text == value)


def item_sql(buy: List[List[Tuple[int, int]]], sell: List[int], sell_price: int) -> str:
    """The buy list per vendor (1310 up), then the shared sell list (1349), and the item_list_items setval."""
    lists = [(lid, f"Armory {k} buy", rows_) for k, (lid, rows_) in enumerate(zip(ARMORY_LISTS, buy))]
    lists.append((SELL_LIST, "Armory sell", [(d, sell_price) for d in sell]))
    out = [GENERATED, ""]
    out += [f"INSERT INTO item_lists (item_list_id, name) VALUES ({lid}, {sql_quote(name)});" for lid, name, _ in lists]
    item_id = ITEM_ROW_BASE
    for lid, _, rows_ in lists:
        for design, price in rows_:
            out.append(
                f"INSERT INTO item_list_items (item_id, item_list_id, design_id, quantity, naquadah) "
                f"VALUES ({item_id}, {lid}, {design}, 1, {price});"
            )
            item_id += 1
    out.append(
        "SELECT pg_catalog.setval('item_lists_item_list_id_seq', GREATEST((SELECT MAX(item_list_id) FROM item_lists), "
        "(SELECT last_value FROM item_lists_item_list_id_seq)), true);"
    )
    out.append(
        "SELECT pg_catalog.setval('item_list_items_item_id_seq', GREATEST((SELECT MAX(item_id) FROM item_list_items), "
        "(SELECT last_value FROM item_list_items_item_id_seq)), true);"
    )
    return "\n".join(out) + "\n"


def template_sql(vendors: List[List[int]], items: Dict[int, dict]) -> str:
    """One Armory template per vendor (1610 up): template 1302's columns, its buy list, the sell list, no repair or recharge."""
    text, row = seed_row(Path("Entities/Seed/entity_templates_debug_area_plaza.sql"), "entity_templates", "template_id", str(VENDOR_TEMPLATE))
    out = [GENERATED, ""]
    for k, reps in enumerate(vendors):
        name = f"Armory {k}: {items[reps[0]]['name']} to {items[reps[-1]]['name']}"
        out.append(
            raw_row(
                "entity_templates", text, row,
                template_id=str(TEMPLATE_BASE + k), template_name=sql_quote(name),
                buy_item_list=str(ARMORY_LISTS[k]), sell_item_list=str(SELL_LIST),
                repair_item_list="NULL", recharge_item_list="NULL",
            )
        )
    return "\n".join(out) + "\n"


def spawn_sql(vendors: List[List[int]], probes: Dict[str, List[str]], grounded: Dict[str, float]) -> str:
    """One stationary spawn per vendor (14110 up) in world 1300, at its grounded probe, as spawn 13006."""
    text, row = seed_row(Path("Worlds/Seed/spawnlist_debug_area_plaza.sql"), "spawnlist", "spawn_id", str(VENDOR_SPAWN))
    out = [GENERATED, ""]
    for k in range(len(vendors)):
        x, _, z = probes[f"DR{k}"]
        out.append(
            raw_row(
                "spawnlist", text, row,
                spawn_id=str(SPAWN_BASE + k), x=x, y=f"{float(probes[f'DR{k}'][1]) - grounded[f'DR{k}']:.2f}", z=z,
                heading=str(HEADING), world_id=str(ARMORY_WORLD), template_id=str(TEMPLATE_BASE + k),
                tag=sql_quote(f"DebugArea_Armory{k}"),
            )
        )
    return "\n".join(out) + "\n"
